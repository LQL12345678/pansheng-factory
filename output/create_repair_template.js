const XLSX = require('xlsx');

// 故障维修记录模板数据
const templateData = [
  // 表头
  ['故障维修记录导入模板'],
  [''],
  ['填写说明：', '', '', '', '', '', '', '', '', ''],
  ['1. 设备ID为必填项，需填写系统中存在的设备ID', '', '', '', '', '', '', '', '', ''],
  ['2. 报修日期格式：YYYY-MM-DD', '', '', '', '', '', '', '', '', ''],
  ['3. 状态可选值：待处理、处理中、已完成、挂起', '', '', '', '', '', '', '', '', ''],
  ['4. 用时(分钟)填写数字', '', '', '', '', '', '', '', '', ''],
  [''],
  ['设备ID*', '报修日期*', '维修人*', '故障描述*', '故障类型', '故障原因', '处理方式', '使用零件', '用时(分钟)', '状态']
];

// 创建一个示例数据行
templateData.push([1, '2026-05-10', '李庆良', '设备无法启动', '电气故障', '接触器损坏', '更换接触器', '接触器×1', 60, '已完成']);

// 创建工作簿
const wb = XLSX.utils.book_new();

// 将数据转换为工作表
const ws = XLSX.utils.aoa_to_sheet(templateData);

// 设置列宽
ws['!cols'] = [
  { wch: 10 },  // 设备ID
  { wch: 12 },  // 报修日期
  { wch: 10 },  // 维修人
  { wch: 30 },  // 故障描述
  { wch: 12 },  // 故障类型
  { wch: 20 },  // 故障原因
  { wch: 20 },  // 处理方式
  { wch: 20 },  // 使用零件
  { wch: 12 },  // 用时(分钟)
  { wch: 10 }   // 状态
];

// 合并标题行
ws['!merges'] = [
  { s: { r: 0, c: 0 }, e: { r: 0, c: 9 } }  // 合并第1行A-J列
];

// 将工作表添加到工作簿
XLSX.utils.book_append_sheet(wb, ws, '故障维修模板');

// 写入文件
XLSX.writeFile(wb, 'C:/Users/Admin/WorkBuddy/2026-05-10-task-1/output/故障维修记录模板.xlsx');

console.log('✅ 故障维修记录模板已生成！');
